/**
 * Liste des domaines d'emails temporaires pour validation
 */
const DISPOSABLE_DOMAINS_SET: Set<string> = new Set(DISPOSABLE_DOMAINS);

/**
 * Vérifie si un domaine est dans la liste noire des emails temporaires
 *
 * @param domain - Le domaine à vérifier (ex: "tempmail.com")
 * @returns true si le domaine est un email temporaire
 */
function isDisposableDomain(domain: string): boolean {
  return DISPOSABLE_DOMAINS_SET.has(domain.toLowerCase());
}

/**
 * Vérifie si un email utilise un domaine temporaire
 *
 * @param email - L'adresse email à vérifier
 * @returns true si l'email utilise un domaine temporaire
 */
function isDisposableEmail(email: string): boolean {
  const domain = email.split('@')[1]?.toLowerCase();
  if (!domain) return false;
  return isDisposableDomain(domain);
}

/**
 * Schéma Zod de validation pour les emails d'administrateur
 * Identique à emailSchema mais avec un message d'erreur plus spécifique
 */
export const adminEmailSchema = z.string({ error: (issue) => issue.input === undefined ? 'Required' : undefined })
  .max(254, 'Email trop long (maximum 254 caractères)')
  .email('Email invalide')
  .refine(
    (email) => !isDisposableEmail(email),
    { message: 'Les adresses email temporaires ou jetables ne sont pas autorisées pour les administrateurs' }
  );
